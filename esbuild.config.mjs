import esbuild from "esbuild";
import fs from "node:fs";
import path from "node:path";
import process from "process";
import builtins from "builtin-modules";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD (Shared by Obsidian Plugin & Web App)
if you want to view the source, please visit the Ratio repository
*/
`;

const footer = `
if (typeof window !== "undefined") {
  if (typeof module !== "undefined" && module.exports) {
    window.RatioCalc = module.exports.RatioCalc;
    window.RatioCalculatorWidget = module.exports.RatioCalculatorWidget;
    window.mountRatioWebApp = module.exports.mountRatioWebApp;
  }
  if (typeof document !== "undefined" && typeof window.mountRatioWebApp === "function") {
    var bootWeb = function () {
      if (document.getElementById("ratio-app") || document.querySelector("[data-ratio-web-root]")) {
        window.mountRatioWebApp();
      }
    };
    if (document.readyState === "loading") {
      document.addEventListener("DOMContentLoaded", bootWeb);
    } else {
      bootWeb();
    }
  }
}
`;

const obsidianUniversalPlugin = {
  name: "obsidian-universal-shim",
  setup(build) {
    build.onResolve({ filter: /^obsidian$/ }, () => ({
      path: "obsidian",
      namespace: "obsidian-shim",
    }));
    build.onLoad({ filter: /.*/, namespace: "obsidian-shim" }, () => ({
      contents: `
        var obs = (typeof require === "function")
          ? (function () { try { return require("obsidian"); } catch (_) { return null; } })()
          : null;
        module.exports = obs || {
          Editor: function () {},
          ItemView: class {},
          MarkdownView: function () {},
          Notice: function () {},
          Plugin: class {},
          PluginSettingTab: class {},
          Setting: class {},
          WorkspaceLeaf: function () {},
          normalizePath: function (p) { return p; },
        };
      `,
      loader: "js",
    }));
  },
};

function writeIndexHtml() {
  const html = `<!DOCTYPE html>
<html lang="zh-CN">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Ratio — 中国房贷利率计算器</title>
  <link rel="stylesheet" href="styles.css">
</head>
<body class="ratio-web-body">
  <main id="ratio-app" data-ratio-web-root></main>
  <footer class="ratio-web-footer">
    Ratio 中国房贷计算器
  </footer>
  <script src="main.js"></script>
</body>
</html>
`;
  fs.writeFileSync(path.resolve("index.html"), html, "utf8");
}

const prod = process.argv[2] === "production";

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  footer: {
    js: footer,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  plugins: [obsidianUniversalPlugin],
  external: [
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
});

writeIndexHtml();

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
