import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Module from 'node:module';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');

/**
 * 利用 Node.js 内置的 TypeScript 类型擦除能力，
 * 将 src/ 下的 TypeScript 模块打包为同时兼容 Obsidian 插件（CommonJS）与浏览器网页版（index.html）的 main.js，
 * 并自动生成网页版入口文件 index.html。
 */
function stripTsTypes(tsCode, filename) {
  if (typeof Module.stripTypeScriptTypes === 'function') {
    return Module.stripTypeScriptTypes(tsCode, {
      mode: 'transform',
      sourceUrl: filename,
    });
  }
  throw new Error('Node.js 22.6+ is required for stripTypeScriptTypes');
}

function readAndStrip(relPath) {
  const fullPath = path.join(rootDir, relPath);
  const src = fs.readFileSync(fullPath, 'utf8');
  let js = stripTsTypes(src, relPath);
  // 移除顶部 import 语句、底部 sourceURL 注释与各类 export 语法，以便合入同一模块作用域
  js = js
    .replace(/^\s*import\s+type\s+[\s\S]*?from\s+['"][^'"]+['"];?\s*$/gm, '')
    .replace(/^\s*import\s+[\s\S]*?from\s+['"][^'"]+['"];?\s*$/gm, '')
    .replace(/^\s*export\s*\{[\s\S]*?\};?\s*$/gm, '')
    .replace(/\/\/# sourceURL=.*$/gm, '')
    .replace(/^\s*export\s+default\s+class\s+/gm, 'class ')
    .replace(
      /^\s*export\s+(async\s+function|function|const|let|var|class)\s+/gm,
      '$1 '
    );
  return `// ─── ${relPath} ───\n${js.trim()}\n`;
}

